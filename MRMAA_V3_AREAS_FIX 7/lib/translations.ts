export function translate(value: unknown, language: AppLanguage): string {
  const text = String(value ?? "");
  const exact = language === "en" ? ENGLISH[text] : REVERSE_ENGLISH[text];
  if (exact) return exact;
  for (const [esPattern, toEnglish, enPattern, toSpanish] of dynamicPairs) {
    const match = text.match(language === "en" ? esPattern : enPattern);
    if (match) return (language === "en" ? toEnglish : toSpanish)(match);
  }
  return text;
}

export function translateMarkup(markup: string, language: AppLanguage): string {
  if (language === "es") return markup;
  return Object.entries(ENGLISH)
    .sort(([a], [b]) => b.length - a.length)
    .reduce((result, [spanish, english]) => result.split(spanish).join(english), markup);
}

export function translateRecord<T extends Record<string, unknown>>(record: T, language: AppLanguage) {
  return Object.fromEntries(
    Object.entries(record).map(([key, value]) => [translate(key, language), value]),
  );
}
